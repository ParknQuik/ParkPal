#!/usr/bin/env node

/**
 * Fetch Secrets from GCP Secret Manager for Mobile App
 *
 * This script fetches Google Maps API keys and other sensitive credentials
 * from GCP Secret Manager and writes them to .env.local for local development.
 *
 * For EAS builds, secrets should be configured via eas.json and EAS Secrets.
 *
 * Usage:
 *   node scripts/fetch-secrets-from-gcp.js
 *
 * Environment Variables (set these in your shell or CI/CD):
 *   - GCP_PROJECT_ID: Your GCP project ID
 *   - GOOGLE_APPLICATION_CREDENTIALS: Path to service account key JSON
 *   - USE_SECRET_MANAGER: Set to 'true' to enable (optional, defaults to false)
 *
 * Prerequisites:
 *   1. GCP project created and Secret Manager API enabled
 *   2. Service account with Secret Manager Secret Accessor role
 *   3. Secrets uploaded to GCP Secret Manager with correct names
 *   4. GOOGLE_APPLICATION_CREDENTIALS environment variable set
 */

const fs = require('fs');
const path = require('path');

// Load environment from shell (not .env file)
// This allows CI/CD to control which secrets to fetch
const GCP_PROJECT_ID = process.env.GCP_PROJECT_ID;
const GOOGLE_APPLICATION_CREDENTIALS = process.env.GOOGLE_APPLICATION_CREDENTIALS;
const USE_SECRET_MANAGER = process.env.USE_SECRET_MANAGER === 'true';
const ENV = process.env.EXPO_PUBLIC_ENV || 'development';

// Define secrets to fetch from GCP (GCP secret name -> local env var name)
const SECRETS_TO_FETCH = {
  'mobile-google-maps-api-key-ios': 'GOOGLE_MAPS_API_KEY_IOS',
  'mobile-google-maps-api-key-android': 'GOOGLE_MAPS_API_KEY_ANDROID',
  'mobile-expo-public-api-url': 'EXPO_PUBLIC_API_URL',
};

/**
 * Fetch a secret from GCP Secret Manager
 */
async function getSecretFromGCP(secretName) {
  try {
    // Lazy load @google-cloud/secret-manager only when needed
    const { SecretManagerServiceClient } = require('@google-cloud/secret-manager');
    const client = new SecretManagerServiceClient();

    const name = `projects/${GCP_PROJECT_ID}/secrets/${secretName}/versions/latest`;
    const [version] = await client.accessSecretVersion({ name });
    const payload = version.payload.data.toString('utf8');

    console.log(`  ✅ Fetched: ${secretName}`);
    return payload;
  } catch (error) {
    console.error(`  ❌ Failed to fetch ${secretName}: ${error.message}`);
    return null;
  }
}

/**
 * Read existing .env.local file
 */
function readExistingEnvLocal() {
  const envLocalPath = path.join(__dirname, '..', '.env.local');
  const existingVars = {};

  if (fs.existsSync(envLocalPath)) {
    const content = fs.readFileSync(envLocalPath, 'utf8');
    content.split('\n').forEach(line => {
      const trimmed = line.trim();
      if (trimmed && !trimmed.startsWith('#')) {
        const [key, ...valueParts] = trimmed.split('=');
        if (key && valueParts.length > 0) {
          existingVars[key.trim()] = valueParts.join('=').trim();
        }
      }
    });
  }

  return existingVars;
}

/**
 * Write secrets to .env.local file
 */
function writeEnvLocal(secrets) {
  const envLocalPath = path.join(__dirname, '..', '.env.local');

  // Read existing vars to preserve non-GCP secrets
  const existingVars = readExistingEnvLocal();

  // Merge with new secrets (new secrets override existing)
  const mergedVars = { ...existingVars, ...secrets };

  // Always include EXPO_PUBLIC_ENV
  if (!mergedVars.EXPO_PUBLIC_ENV) {
    mergedVars.EXPO_PUBLIC_ENV = ENV;
  }

  // Build .env.local content
  const lines = [
    '# Auto-generated by fetch-secrets-from-gcp.js',
    `# Last updated: ${new Date().toISOString()}`,
    '# DO NOT COMMIT THIS FILE - It contains sensitive API keys',
    '',
    '# ============================================',
    '# ENVIRONMENT',
    '# ============================================',
    `EXPO_PUBLIC_ENV=${mergedVars.EXPO_PUBLIC_ENV}`,
    '',
  ];

  // Add API URL if available
  if (mergedVars.EXPO_PUBLIC_API_URL) {
    lines.push('# ============================================');
    lines.push('# BACKEND API');
    lines.push('# ============================================');
    lines.push(`EXPO_PUBLIC_API_URL=${mergedVars.EXPO_PUBLIC_API_URL}`);
    lines.push('');
  }

  // Add Google Maps API keys
  lines.push('# ============================================');
  lines.push('# GOOGLE MAPS API KEYS (from GCP Secret Manager)');
  lines.push('# ============================================');

  if (mergedVars.GOOGLE_MAPS_API_KEY_IOS) {
    lines.push(`GOOGLE_MAPS_API_KEY_IOS=${mergedVars.GOOGLE_MAPS_API_KEY_IOS}`);
  }

  if (mergedVars.GOOGLE_MAPS_API_KEY_ANDROID) {
    lines.push(`GOOGLE_MAPS_API_KEY_ANDROID=${mergedVars.GOOGLE_MAPS_API_KEY_ANDROID}`);
  }

  // Add any other variables that were in the existing file
  const knownKeys = new Set([
    'EXPO_PUBLIC_ENV',
    'EXPO_PUBLIC_API_URL',
    'GOOGLE_MAPS_API_KEY_IOS',
    'GOOGLE_MAPS_API_KEY_ANDROID'
  ]);

  const otherVars = Object.entries(mergedVars)
    .filter(([key]) => !knownKeys.has(key));

  if (otherVars.length > 0) {
    lines.push('');
    lines.push('# ============================================');
    lines.push('# OTHER VARIABLES');
    lines.push('# ============================================');
    otherVars.forEach(([key, value]) => {
      lines.push(`${key}=${value}`);
    });
  }

  lines.push('');

  fs.writeFileSync(envLocalPath, lines.join('\n'), 'utf8');
  console.log(`\n📝 Written secrets to: ${envLocalPath}`);
}

/**
 * Check if .env.local already has valid secrets
 */
function hasValidLocalSecrets() {
  const existing = readExistingEnvLocal();

  const hasIosKey = existing.GOOGLE_MAPS_API_KEY_IOS &&
                    !existing.GOOGLE_MAPS_API_KEY_IOS.includes('YOUR_');
  const hasAndroidKey = existing.GOOGLE_MAPS_API_KEY_ANDROID &&
                        !existing.GOOGLE_MAPS_API_KEY_ANDROID.includes('YOUR_');

  return hasIosKey && hasAndroidKey;
}

/**
 * Main function
 */
async function fetchSecrets() {
  console.log('\n🔐 Fetching secrets from GCP Secret Manager...\n');

  // Check if we should use Secret Manager
  if (!USE_SECRET_MANAGER) {
    console.log('ℹ️  USE_SECRET_MANAGER is not set to "true"');

    // Check if local secrets exist
    if (hasValidLocalSecrets()) {
      console.log('✅ Using existing secrets from .env.local');
      console.log('💡 To fetch from GCP, set: USE_SECRET_MANAGER=true\n');
      return;
    } else {
      console.log('⚠️  No valid local secrets found in .env.local');
      console.log('💡 Options:');
      console.log('   1. Set USE_SECRET_MANAGER=true and configure GCP credentials');
      console.log('   2. Manually copy .env.example to .env.local and add your keys\n');
      process.exit(1);
    }
  }

  // Validate GCP configuration
  if (!GCP_PROJECT_ID) {
    console.error('❌ Error: GCP_PROJECT_ID environment variable not set');
    console.log('💡 Set it in your shell: export GCP_PROJECT_ID=your-project-id\n');
    process.exit(1);
  }

  if (!GOOGLE_APPLICATION_CREDENTIALS) {
    console.error('❌ Error: GOOGLE_APPLICATION_CREDENTIALS environment variable not set');
    console.log('💡 Set it in your shell: export GOOGLE_APPLICATION_CREDENTIALS=/path/to/key.json\n');
    process.exit(1);
  }

  if (!fs.existsSync(GOOGLE_APPLICATION_CREDENTIALS)) {
    console.error(`❌ Error: Service account key file not found: ${GOOGLE_APPLICATION_CREDENTIALS}`);
    process.exit(1);
  }

  console.log(`📦 GCP Project: ${GCP_PROJECT_ID}`);
  console.log(`🔑 Service Account: ${GOOGLE_APPLICATION_CREDENTIALS}`);
  console.log(`🌍 Environment: ${ENV}\n`);

  // Check if @google-cloud/secret-manager is installed
  try {
    require.resolve('@google-cloud/secret-manager');
  } catch (e) {
    console.error('❌ Error: @google-cloud/secret-manager not installed');
    console.log('💡 Install it: npm install @google-cloud/secret-manager\n');
    process.exit(1);
  }

  console.log('🔄 Fetching secrets...\n');

  const secrets = {};
  let successCount = 0;
  let failCount = 0;

  // Fetch each secret
  for (const [gcpSecretName, envVarName] of Object.entries(SECRETS_TO_FETCH)) {
    const value = await getSecretFromGCP(gcpSecretName);

    if (value) {
      secrets[envVarName] = value;
      successCount++;
    } else {
      failCount++;
    }
  }

  console.log('\n' + '='.repeat(60));
  console.log('📊 Fetch Summary:');
  console.log(`  ✅ Successful: ${successCount}`);
  console.log(`  ❌ Failed: ${failCount}`);
  console.log('='.repeat(60));

  if (successCount === 0) {
    console.error('\n❌ No secrets were fetched. Please check:');
    console.log('  1. Secret names in GCP Secret Manager match expected names');
    console.log('  2. Service account has Secret Manager Secret Accessor role');
    console.log('  3. Secrets exist in the specified GCP project\n');
    process.exit(1);
  }

  // Write to .env.local
  writeEnvLocal(secrets);

  console.log('\n✨ Success! Secrets have been fetched and saved.\n');

  if (failCount > 0) {
    console.log('⚠️  Some secrets failed to fetch. Your app may not work correctly.');
    console.log('💡 Check the errors above and ensure all secrets exist in GCP.\n');
  }

  console.log('📝 Next steps:');
  console.log('  1. Run: npm start (or expo start)');
  console.log('  2. Verify maps functionality works in the app');
  console.log('  3. For EAS builds, configure secrets in eas.json\n');
}

// Handle script errors
process.on('unhandledRejection', (error) => {
  console.error('\n❌ Fatal error:', error.message);
  if (error.code === 'ENOENT') {
    console.log('💡 Make sure the service account key file exists');
  } else if (error.code === 5) {
    console.log('💡 Permission denied. Check service account has Secret Manager Secret Accessor role');
  } else if (error.code === 7) {
    console.log('💡 Permission denied. Check GCP_PROJECT_ID is correct');
  }
  console.log('');
  process.exit(1);
});

// Run the script
if (require.main === module) {
  fetchSecrets().catch((error) => {
    console.error('\n❌ Fatal error:', error);
    process.exit(1);
  });
}

module.exports = { fetchSecrets };
